suppressMessages({library(data.table)})
setwd("G:/GCModeller/test/demo/HTS/GSVA/brca_tcga_pub2015_mogsva")
S <- as.matrix(fread("scores.csv"), rownames = 1)
R <- as.matrix(fread("raw_scores.csv"), rownames = 1)
C <- as.matrix(fread("consistency.csv"), rownames = 1)
P <- as.matrix(fread("pooled_scores.csv"), rownames = 1)
cat("dims", dim(S), dim(R), dim(C), dim(P), "\n")
cat("NA scores", sum(is.na(S)), "NA pooled", sum(is.na(P)), "\n")
cat("consistency uniq", length(unique(as.vector(C))), "\n")
print(sort(table(round(as.vector(C), 3)), decreasing = TRUE)[1:10])
cat("cons mean range", range(rowMeans(C)), "\n")
cat("score range", range(S, na.rm = TRUE), "\n")
pv <- apply(S, 1, var)
cat("pathway var quantiles\n"); print(quantile(pv, c(0, .25, .5, .75, .9, .99, 1)))
cat("mean var raw", mean(apply(R, 1, var)), " fused", mean(pv), "\n")
sig <- fread("significance.csv")
cat("sig n", nrow(sig), " q<0.01", sum(sig$q_value < 0.01), " q<0.05", sum(sig$q_value < 0.05), " q<0.1", sum(sig$q_value < 0.1), "\n")
print(head(sig[order(q_value)], 10))
w <- fread("weights.csv")
print(w[, .(mean_w = mean(weight), skipped = sum(skipped)), by = omics])
cv <- fread("coverage.csv")
print(cv[, .(median_members = median(member_count), mean_members = mean(member_count)), by = omics])
pd <- fread("pooled_diagnostics.csv")
cat("pooled r mean", mean(pd$pearson_r), " median", median(pd$pearson_r), "\n")
print(quantile(pd$pearson_r, c(.05, .25, .5, .75, .95)))
cat("r>0.9:", sum(pd$pearson_r > 0.9), "/", nrow(pd), "\n")
cat("scores-only pathways", length(setdiff(rownames(S), rownames(P))), " overlap", length(intersect(rownames(S), rownames(P))), "\n")
cat("top var pathways\n")
print(head(sort(pv, decreasing = TRUE), 15))
