// 排序与查找原语（ILCuda）
//
// 面向"每个基因一段"的对照细胞排序值：段长可达 18000（对照细胞数），
// 远超单个 block 的共享内存容量，因此不使用双调排序，而是分段 LSD 基数排序。
//
// 浮点排序走"位模式变换"：
//   * 正数：符号位取反（0x80000000 ^ bits），使无符号比较等价于数值比较
//   * 负数：整体按位取反
//   * -0.0 归一到 +0.0，NaN 统一沉到段尾
// 这样基数排序的无符号桶序与数值升序严格一致。
//
// 数值口径：段内"值相同"的元素在排序后不可区分，因此散播阶段的原子偏移
// 不会影响输出的有序数组（多重集合唯一）。需要下标的场合（TopK）另走
// 阈值选择 + 按下标稳定收集，结果确定。
//
// 宏前缀 ILCUDA_SORT_，符号前缀 ilcudaSort / ilcudaSeg。
